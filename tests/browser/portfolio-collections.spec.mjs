import { test, expect } from '@playwright/test'
import { installFixtures } from './fixtures.mjs'

test('filters project/company cards and plays video on the same page', async ({ page }) => {
  await installFixtures(page)
  await page.goto('/portfolio')
  await expect(page.locator('.portfolio-grid-card-link')).toHaveCount(2)
  await expect(page.locator('iframe')).toHaveCount(0)
  await page.getByRole('button', { name: /^Interviews/ }).click()
  await expect(page.locator('.portfolio-grid-card-link')).toHaveCount(1)
  await expect(page).toHaveURL(/type=interview/)
  const watch = page.getByRole('button', { name: 'Watch QA Company Collection videos without leaving the portfolio' })
  await watch.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('iframe')).toHaveAttribute('src', /youtube-nocookie.com\/embed\/M7lc1UVf-VE/)
  await expect(dialog.locator('iframe')).toHaveAttribute('referrerpolicy', 'strict-origin-when-cross-origin')
  await expect(page).toHaveURL(/\/portfolio\?type=interview$/)
  await dialog.getByRole('button', { name: 'Close media viewer' }).click()
  await expect(page.locator('iframe')).toHaveCount(0)
  await expect(watch).toBeFocused()
  await page.getByRole('link', { name: 'View the QA Company Collection case study' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('QA Company Collection')
  await expect(page.locator('.portfolio-case-gallery-item')).toHaveCount(1)
  await page.getByRole('button', { name: /^Reels/ }).click()
  await page.getByRole('button', { name: 'Watch QA reels', exact: true }).click()
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
})

