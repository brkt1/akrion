test('admin can create a new company collection with a reel on mobile', async ({ page }) => {
  const fixture = await installFixtures(page, { admin: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/admin/portfolio?new=1')
  await page.getByLabel('Collection type', { exact: true }).selectOption('company')
  await page.locator('#project-title').fill('Local QA new company')
  await page.locator('#project-slug').fill('local-qa-new-company')
  await page.locator('#project-category').fill('Video production')
  await page.locator('#project-cardDescription').fill('Local-only collection test.')
  await page.getByRole('button', { name: '+ Add video', exact: true }).click()
  const row = page.locator('.admin-portfolio-media-item').last()
  await row.getByRole('textbox', { name: 'Media title', exact: true }).fill('Local QA reel')
  await row.getByRole('combobox', { name: 'Content type', exact: true }).selectOption('reels')
  await row.getByRole('textbox', { name: 'YouTube or video URL', exact: true }).fill('https://youtube.com/shorts/M7lc1UVf-VE')
  await expect(row.getByLabel('Orientation', { exact: true })).toHaveValue('portrait')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByText('Project saved with its current workflow status.')).toBeVisible()
  expect(fixture.writes).toHaveLength(1)
  expect(fixture.writes[0].collection_type).toBe('company')
  expect(fixture.writes[0].status).toBe('draft')
  expect(fixture.writes[0].media_items[0].category).toBe('reels')
  expect(fixture.writes[0].media_items[0].orientation).toBe('portrait')
})

for (const width of [320, 375, 390, 430, 768, 1440]) {
  test(`collection layout has no horizontal overflow at ${width}px`, async ({ page }) => {
    await installFixtures(page)
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/portfolio')
    await expect(page.locator('.portfolio-grid-card-link')).toHaveCount(2)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    await page.getByRole('button', { name: 'Watch QA Company Collection videos without leaving the portfolio' }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    const bounds = await page.getByRole('dialog').boundingBox()
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width + 1)
    await page.getByRole('dialog').getByRole('button', { name: 'Close media viewer' }).click()
    if (width === 390 || width === 1440) await page.screenshot({ path: `test-results/portfolio-collections-${width}.png` })
  })
}
